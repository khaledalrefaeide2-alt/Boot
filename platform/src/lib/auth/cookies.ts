/**
 * أسماء كوكيز الجلسة — في وحدةٍ لا تلمس الخادم.
 *
 * `session.ts` يبدأ بـ`import 'server-only'`، فلا يستطيع الوسيط
 * (`proxy.ts`) أن يقرأ منه شيئاً — وكان يُعيد كتابة الاسم حرفاً بحرف:
 * `const SESSION_COOKIE = 'mm_session'` في الملفّين.
 *
 * وثمنُ ذلك أنّ تغيير الاسم في أحدهما لا يُعطب البناء: الوسيط يبحث عن
 * كوكي لا وجود له، فيرى كلّ زائر «بلا جلسة» ويُحوّله إلى تسجيل الدخول —
 * ومن سجّل دخوله يُحوَّل كذلك، فلا يدخل أحدٌ الموقعَ أبداً.
 */

/**
 * بادئة `__Host-` في الإنتاج.
 *
 * ★ النطاق `hstgr.cloud` ليس في قائمة النطاقات العامة (Public Suffix List).
 *
 *   فكلّ خادمٍ آخر عند المزوّد بعنوان `srvXXXX.hstgr.cloud` «من الموقع
 *   نفسه» في عين المتصفّح، ويستطيع أن يزرع كوكي بـ`Domain=hstgr.cloud`
 *   تصل إلى منصّتنا. وNext يأخذ آخر كوكي بالاسم نفسه، والمتصفّح يرتّب
 *   الأحدث آخراً — فكوكي زُرعت بعد دخول الموظّف تغلب كوكيه: تُخرجه من
 *   المنصّة كلّما زار صفحة الخصم، أو تُبدّل جلسته بجلسةٍ يملكها غيره.
 *
 *   والبادئة يفرضها المتصفّح نفسه: كوكي `__Host-` لا تُقبل إلا بلا
 *   `Domain` وعلى المشفَّر وبمسار `/` — فلا يستطيع جارٌ أن يزرعها.
 *
 *   وهي للإنتاج وحده لأنّها تشترط `Secure`، والتطوير على عنوانٍ محلّي
 *   في الشبكة يجري على http. وتغيير الاسم يُخرج كلّ المستخدمين مرّة واحدة
 *   عند النشر الأوّل بعده.
 *
 * `process.env.NODE_ENV` يُكتب حرفياً في حزمة الواجهة وفي الوسيط عند
 * البناء، فالاسم واحدٌ في الخادم والوسيط والمتصفّح.
 */
const COOKIE_PREFIX = process.env.NODE_ENV === 'production' ? '__Host-' : '';

/** كوكي الجلسة — httpOnly، لا تقرؤه الواجهة */
export const SESSION_COOKIE = `${COOKIE_PREFIX}mm_session`;

/** سرّ CSRF — مقروء من الواجهة عمداً (نمط الإرسال المزدوج) */
export const CSRF_COOKIE = `${COOKIE_PREFIX}mm_csrf`;

/** الجهاز الموثوق — دخل منه صاحب الحساب قبلاً، فلا يحجبه حدّ التخمين الموزَّع */
export const DEVICE_COOKIE = `${COOKIE_PREFIX}mm_device`;

/** أسماء ما قبل البادئة — تُمحى عند الدخول كي لا تبقى في المتصفّح بلا عمل */
export const LEGACY_COOKIES = COOKIE_PREFIX ? ['mm_session', 'mm_csrf'] : [];

/**
 * خيارات محو كوكي.
 *
 * ★ `cookies.delete(name)` وحدها لا تمحو كوكي `__Host-`.
 *
 *   Next يمحو بكتابة الكوكي فارغةً منتهية — بلا `Secure`. والمتصفّح يرفض
 *   أيّ `Set-Cookie` لاسمٍ بالبادئة ما لم يحمل `Secure` و`Path=/`، فيبقى
 *   الكوكي حيّاً: يضغط الموظّف «خروج» فيبقى داخلاً، وحلقة «الجلسة انتهت»
 *   في الوسيط تدور بلا نهاية.
 */
export function cookieDeletion(name: string): { name: string; path: '/'; secure: boolean } {
  return { name, path: '/', secure: process.env.NODE_ENV === 'production' };
}

/**
 * علامة «الجلسة انتهت» في رابط تسجيل الدخول.
 *
 * هي ما يكسر حلقة التحويل بين الوسيط والخادم: الوسيط يثق بوجود الكوكي،
 * والخادم يثق بصحّتها. فإذا حمل المتصفّح كوكيّاً لجلسةٍ انتهت، تدافع
 * الاثنان إلى الأبد — والعلامة هي قول الخادم للوسيط: «سألتُ القاعدة،
 * وهذه الكوكي ميّتة، فلا تُعدني إلى الداخل».
 */
export const SESSION_EXPIRED_PARAM = 'expired';

/**
 * مسار الصفحة الحالية — يكتبه الوسيط في الطلب لكلّ صفحة.
 *
 * التخطيط لا يعرف مسار الصفحة، ولا يُعاد تنفيذه عند التنقّل داخل الموقع.
 * فيُكتب المسار هنا ليعرف `getSession` أيّ صفحةٍ تُصيَّر الآن — وهو ما
 * يمنع صاحب كلمة المرور المؤقتة من التنقّل إلى غير صفحة تغييرها. والوسيط
 * يكتبه فوق أيّ قيمةٍ أرسلها العميل، فلا يُزوَّر.
 */
export const PAGE_PATH_HEADER = 'x-mm-page-path';

/** رمز الخطأ حين تمنع كلمةُ المرور المؤقتة الطلب — تقرؤه الواجهة فتحوّل */
export const PASSWORD_CHANGE_REQUIRED = 'PASSWORD_CHANGE_REQUIRED';

/** الصفحة الوحيدة المتاحة قبل تغيير كلمة المرور المؤقتة */
export const PASSWORD_CHANGE_PAGE = '/profile';

/**
 * وجهةٌ داخلية آمنة من معامل `next`.
 *
 * ★ `startsWith('/')` وحدها لا تكفي، وكان ذلك هو الفحص.
 *
 *   `//evil.com/x` يبدأ بشرطة مائلة، وهو عنوانٌ **كامل** بروتوكولُه
 *   بروتوكولُ الصفحة. فمن فتح
 *   `https://<المنصة>/login?next=//evil.com` رأى رابطاً صحيحاً يحمل
 *   اسم مؤسّسته، وأدخل كلمة مروره في صفحة المنصة الحقيقية، ثمّ وجد
 *   نفسه على موقع الخصم بعد نجاح الدخول — وهو أنفع ما يكون للتصيّد،
 *   لأنّ الضحية دخل للتوّ ويتوقّع صفحةً تالية.
 *
 *   و`/\evil.com` كذلك: متصفّحات تقرأ الشرطة المائلة العكسية مائلةً.
 *
 * والشرط هنا: شرطةٌ واحدة، ثمّ ما ليس شرطةً ولا شرطةً عكسية.
 *
 * دالّة خالصة — تُفحص وحدها، وتُستعمل في الواجهة والخادم معاً.
 */
export function safeNextPath(value: string | null | undefined): string | null {
  if (!value) return null;
  if (!value.startsWith('/')) return null;
  if (value.startsWith('//') || value.startsWith('/\\')) return null;
  // «/..» تخرج من الجذر في بعض القراءات، ولا وجهة داخلية تحتاجها
  if (value.includes('..')) return null;
  return value;
}
