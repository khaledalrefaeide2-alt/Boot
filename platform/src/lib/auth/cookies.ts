/**
 * أسماء كوكيز الجلسة — في وحدةٍ لا تلمس الخادم.
 *
 * `session.ts` يبدأ بـ`import 'server-only'`، فلا يستطيع الوسيط
 * (`proxy.ts`) أن يقرأ منه شيئاً — وكان يُعيد كتابة الاسم حرفاً بحرف:
 * `const SESSION_COOKIE = 'mm_session'` في الملفّين.
 *
 * وثمنُ ذلك أنّ تغيير الاسم في أحدهما لا يُعطب البناء: الوسيط يبحث عن
 * كوكي لا وجود له، فيرى كلّ زائر «بلا جلسة» ويُحوّله إلى تسجيل الدخول —
 * ومن سجّل دخوله يُحوَّل كذلك، فلا يدخل أحدٌ الموقعَ أبداً.
 */

/** كوكي الجلسة — httpOnly، لا تقرؤه الواجهة */
export const SESSION_COOKIE = 'mm_session';

/** سرّ CSRF — مقروء من الواجهة عمداً (نمط الإرسال المزدوج) */
export const CSRF_COOKIE = 'mm_csrf';

/**
 * علامة «الجلسة انتهت» في رابط تسجيل الدخول.
 *
 * هي ما يكسر حلقة التحويل بين الوسيط والخادم: الوسيط يثق بوجود الكوكي،
 * والخادم يثق بصحّتها. فإذا حمل المتصفّح كوكيّاً لجلسةٍ انتهت، تدافع
 * الاثنان إلى الأبد — والعلامة هي قول الخادم للوسيط: «سألتُ القاعدة،
 * وهذه الكوكي ميّتة، فلا تُعدني إلى الداخل».
 */
export const SESSION_EXPIRED_PARAM = 'expired';

/**
 * وجهةٌ داخلية آمنة من معامل `next`.
 *
 * ★ `startsWith('/')` وحدها لا تكفي، وكان ذلك هو الفحص.
 *
 *   `//evil.com/x` يبدأ بشرطة مائلة، وهو عنوانٌ **كامل** بروتوكولُه
 *   بروتوكولُ الصفحة. فمن فتح
 *   `https://<المنصة>/login?next=//evil.com` رأى رابطاً صحيحاً يحمل
 *   اسم مؤسّسته، وأدخل كلمة مروره في صفحة المنصة الحقيقية، ثمّ وجد
 *   نفسه على موقع الخصم بعد نجاح الدخول — وهو أنفع ما يكون للتصيّد،
 *   لأنّ الضحية دخل للتوّ ويتوقّع صفحةً تالية.
 *
 *   و`/\evil.com` كذلك: متصفّحات تقرأ الشرطة المائلة العكسية مائلةً.
 *
 * والشرط هنا: شرطةٌ واحدة، ثمّ ما ليس شرطةً ولا شرطةً عكسية.
 *
 * دالّة خالصة — تُفحص وحدها، وتُستعمل في الواجهة والخادم معاً.
 */
export function safeNextPath(value: string | null | undefined): string | null {
  if (!value) return null;
  if (!value.startsWith('/')) return null;
  if (value.startsWith('//') || value.startsWith('/\\')) return null;
  // «/..» تخرج من الجذر في بعض القراءات، ولا وجهة داخلية تحتاجها
  if (value.includes('..')) return null;
  return value;
}
