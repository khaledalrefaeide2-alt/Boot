/*
 * تمييز الأمر من السؤال، وتوحيد نصّه.
 *
 * مفصولٌ عن `capture.ts` عمداً: ذاك يلمس القاعدة والمزوّد، فلا يُحمَّل إلا
 * في الخادم ولا يُفحص إلا ببيئة كاملة. وهذا حسابٌ على نصّ لا غير، فيُفحص
 * وحده — وهما أكثر ما يحتاج الفحص في هذا الباب.
 */

/** أقصى ما يُستخرج من رسالة واحدة — الرسالة الواحدة لا تحمل دليلاً كاملاً */
export const MAX_PER_MESSAGE = 3;

/** أقصر ما يُعدّ توجيهاً، وأطول ما يُقبل قاعدةً واحدة */
export const MIN_INSTRUCTION = 10;
export const MAX_INSTRUCTION = 400;

/**
 * علامات الأمر في العربية.
 *
 * مرشّحٌ أوّليّ لا حكمٌ نهائي. وهو ضروري: بدونه يُستدعى النموذج لكل رسالة
 * تُكتب للمساعد، وأكثرها أسئلة («كم منشوراً…»، «ما أبرز…») فتُدفع كلفة
 * استخراجٍ لا يجد شيئاً في كل مرة. وبه لا يُستدعى إلا حين يظهر أثر أمر.
 *
 * والخطأ هنا رخيص في الاتجاهين: مرشّحٌ فات عليه توجيه يعني أن المستخدم
 * يكتبه يدوياً كما كان، ومرشّحٌ فتح الباب لسؤال يعني استدعاءً واحداً
 * يعود فارغاً. ولذلك تُكتب الأنماط بلا حدود كلمات: `\b` في جافاسكربت
 * معرّفة على [A-Za-z0-9_] وحدها، فهي لا تعرف الحرف العربي أصلاً وتردّ كل
 * نمط هنا. والعربية تلصق السوابق بالكلمة — «واعتبر»، «فاجعل» — فحتى
 * الحدّ الصحيح يونيكوديّاً كان سيُفوّت أكثر ممّا يمنع.
 */
const DIRECTIVE_MARKERS: RegExp[] = [
  /اعتبر/,
  /لا\s*تعتبر/,
  /صنّ?ف/,
  /لا\s*تصنّ?ف/,
  /اجعل/,
  /تجاهل/,
  /انتبه/,
  /استثن/,
  /يجب\s+أ?ن/,
  /لا\s+يجب/,
  /من\s+الآ?ن\s+فصاعدا?/,
  /دائما/,
  /كل\s+منشور/,
  /أي\s+منشور/,
  /احسب/,
  /ركّ?ز\s+على/,
  /قاعدة\s+عامة/,
  /تعامل\s+مع/,
];

/** هل في الرسالة أثرُ أمرٍ يستحقّ الاستخراج؟ — دالّة خالصة قابلة للفحص */
export function looksLikeDirective(message: string): boolean {
  const text = message.trim();
  if (text.length < MIN_INSTRUCTION) return false;
  return DIRECTIVE_MARKERS.some((marker) => marker.test(text));
}

/** توحيد النصّ للمقارنة — فلا يُحفظ التوجيه نفسه مرّتين بفارق مسافة */
export function normalizeInstruction(text: string): string {
  return text
    .trim()
    .replace(/[\u064B-\u0652\u0670]/g, '') // التشكيل
    .replace(/[أإآ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/[^\p{L}\p{N}\s]/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}
