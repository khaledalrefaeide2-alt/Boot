export interface LexiconMatch {
  key: LexiconKey;
  hint: string;
  /** الألفاظ التي وردت فعلاً، بصورتها في القاموس */
  terms: string[];
}

/**
 * مطابقة القواميس على نصّ المنشور.
 *
 * والمطابقة على النصّ المطبَّع، والمُخرَج ألفاظُ القاموس لا مقتطفات
 * النصّ: المقتطف دليلٌ يُطابَق بالأصل حرفاً بحرف، وهذه إشارةٌ إلى موضع
 * النظر.
 *
 * ★ ولا تُستعمل حدود الكلمات (`\b`) — هي لا تعمل مع العربية في جافاسكربت
 *   أصلاً، وتُسقِط المطابقة كلّها بصمت.
 *
 * ★ فالقصيرُ يُطابَق بحدوده، والطويلُ بتضمينه.
 *
 *   «لن» حرفُ نفي، وهو داخل «أعلنت» و«لنا». و«دون» داخل «الفاسدون».
 *   والمطابقة بالتضمين تلتقطهما في كلّ خبرٍ محايد، فتملأ قائمة المراجع
 *   بضجيجٍ يُعلَّم تجاهله — وحين تُتجاهَل القائمة تسقط معها المطابقاتُ
 *   الصحيحة. (وهذا ما أظهره الفحص: «أعلنت الوزارة بدء استقبال الطلبات»
 *   كان يُطابق «لن».)
 *
 *   والطويلُ عكسه: «فاسد» يجب أن تُطابق «الفاسد» و«فاسدون»، والتضمين
 *   هو ما يلتقط السوابق واللواحق. فالحدّ ثلاثة محارف: ما دونها وما
 *   عندها أدواتٌ تُطابَق بحدودها، وما فوقها كلماتٌ تُطابَق بتضمينها.
 */
const SHORT_TERM = 3;

export function matchLexicons(text: string): LexiconMatch[] {
  if (!text.trim()) return [];
  const haystack = ` ${normalizeForMatch(text)} `;

  const matches: LexiconMatch[] = [];
  for (const lexicon of LEXICONS) {
    const terms = lexicon.terms.filter((term) => {
      const needle = normalizeArabic(term);
      return needle.length <= SHORT_TERM
        ? haystack.includes(` ${needle} `)
        : haystack.includes(needle);
    });
    if (terms.length > 0) matches.push({ key: lexicon.key, hint: lexicon.hint, terms });
  }
  return matches;
}

/** الألفاظ المطابِقة كلها في قائمة واحدة — لحفظها مع التحليل */
export function matchedTerms(matches: LexiconMatch[]): string[] {
  return [...new Set(matches.flatMap((match) => match.terms))].slice(0, MAX_MATCHED_KEYWORDS);
}

/**
 * كتلةٌ تُرفَق بنصّ المنشور تقول للنموذج أين ينظر.
 *
 * وتُصاغ أمراً بالفحص لا حكماً مسبقاً: «وردت هذه الألفاظ، افحص سياقها»
 * لا «هذا المنشور فيه تحريض». والفرق ليس في الأدب — النموذج الذي يُعطى
 * حكماً يُصدّقه ويبني عليه، والذي يُعطى سؤالاً يقرأ النصّ ليجيب عنه.
 */
export function lexiconHintBlock(matches: LexiconMatch[]): string {
  if (matches.length === 0) return '';

  const lines = matches.map((match) => `- ${match.hint}\n  الألفاظ: ${match.terms.join('، ')}`);

  return [
    '## ألفاظ استدعت الفحص',
    '',
    'وردت في النصّ الألفاظ التالية. **وجودها لا يصنّف شيئاً** — اقرأ سياق',
    'كلٍّ منها وقرّر: أهي مقولةٌ متبنّاة، أم منقولةٌ عن غير، أم منفيّة، أم',
    'مذكورةٌ للتنديد بها؟ وإن لم يكن لها أثرٌ في المعنى فتجاهلها.',
    '',
    ...lines,
  ].join('\n');
}
