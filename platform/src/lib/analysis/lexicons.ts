/**
 * قواميس الكشف — أداةُ التفات لا أداةُ حكم.
 *
 * ★ والقاعدة التي يقوم عليها هذا الملفّ كلّه: الكلمة لا تُصنِّف.
 *
 *   «انتشرت شائعة تقول إن المؤسسة فاسدة، لكن الوثائق تنفي ذلك» فيه
 *   «شائعة» و«فاسدة»، وهو ينفي الشائعة لا يروّجها. ومحرّكُ كلماتٍ يقرؤه
 *   سلبيّاً مروّجاً للشائعة — وهو عكس معناه تماماً.
 *
 *   فما يُخرجه هذا الملفّ **إشارةٌ إلى موضع النظر** تُمرَّر إلى النموذج
 *   ليقرأ سياقها، وتُحفظ مع التحليل ليُراجَع الحكم: مراجعٌ يرى «كلهم»
 *   و«خونة» يفهم من أين جاء «تعميم» و«تخوين». ولا يصنّف شيئاً بنفسه.
 *
 * ★ والنصّ الأصلي لا يُمسّ.
 *
 *   التطبيع هنا للمطابقة وحدها. والنصّ الذي يُرسَل إلى النموذج، والمقتطف
 *   الذي يُحفظ دليلاً، كلاهما من الأصل حرفاً بحرف — وإلا سقطت مطابقة
 *   الدليل بنصّ المنشور، وهي الحارس الذي يمنع اختلاق الاقتباسات.
 */
import { normalizeArabic } from './text';

/** أقصى ما يُحفظ من ألفاظ مطابِقة — القائمة دليلٌ لا أرشيف */
export const MAX_MATCHED_KEYWORDS = 12;

/**
 * فكّ التمويه.
 *
 * محاولاتُ تجاوز الرصد تفصل حروف الكلمة: «فـا.سـد»، «ك*ذاب»،
 * «ح ر ا م ي». والتطويل والمحارف الصفرية تُزال أوّلاً، ثمّ الفواصل بين
 * حرفين متلاصقين، ثمّ الكلمة المبعثرة حرفاً حرفاً.
 *
 * ★ ولا تُدمج الكلمات العادية.
 *
 *   القاعدة الوحيدة الآمنة: لا يُزال فاصلٌ إلا بين حرفين لا مسافة
 *   بينهما أصلاً (نقطةٌ أو نجمة داخل كلمة)، أو في سلسلةٍ من أحرفٍ مفردة
 *   متتابعة. أمّا «في المدينة» فمسافةٌ بين كلمتين تامّتين، ولو دُمجت
 *   لصارت كلّ جملة كلمةً واحدة لا تطابق شيئاً.
 */
export function deobfuscate(text: string): string {
  return (
    text
      // التطويل والمحارف الصفرية: تمويهٌ صامت لا يُرى في الشاشة
      .replace(/[ـ​-‏‪-‮﻿]/g, '')
      // فاصلٌ داخل كلمة: «فا.سد» و«ك*ذاب» — بين حرفين بلا مسافة
      .replace(/(\p{L})[.\*_+\-–~^'"`|/\\]+(?=\p{L})/gu, '$1')
      // رقمٌ داخل كلمة عربية: «فا7سد»
      .replace(/(\p{Script=Arabic})[0-9]+(?=\p{Script=Arabic})/gu, '$1')
      // كلمةٌ مبعثرة: ثلاثة أحرف مفردة فأكثر يفصلها فراغ واحد
      .replace(/(?<![\p{L}])((?:\p{L}\s){2,}\p{L})(?![\p{L}])/gu, (match) =>
        match.replace(/\s+/g, ''),
      )
  );
}

/**
 * التطبيع الكامل للمطابقة: فكّ تمويه، وتوحيد الهمزة، وإسقاط الترقيم.
 *
 * والترقيم يُسقَط لأن المطابقة تعتمد المسافات حدوداً للكلمة القصيرة
 * (انظر `matchLexicons`): «فاسد،» بفاصلةٍ لاصقة لا تُطابق «فاسد» بدونها.
 */
export function normalizeForMatch(text: string): string {
  return normalizeArabic(deobfuscate(text))
    .replace(/[^\p{L}\p{N}\s]/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

