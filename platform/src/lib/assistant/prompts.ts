/** عنوان مختصر للمحادثة يُشتقّ من أول سؤال */
export function deriveTitle(question: string): string {
  const clean = question.replace(/\s+/g, ' ').trim();
  return clean.length <= 60 ? clean : `${clean.slice(0, 57)}…`;
}

