-- تاريخ بدءٍ ثابت بدل النافذة المتحرّكة.
--
-- كان الحصر «ما استُخرج اليوم» يُعاد حسابه كلّ يوم. وثمنُه أنّ ما وصل أمس
-- ولم تبلغه المكنسة — لانقطاع العامل، أو لبلوغ السقف اليومي — يسقط من
-- حسابها عند منتصف الليل ولا تعود إليه أبداً. فكلّ ليلة تُخلّف وراءها
-- منشوراتٍ «غير محسومة» إلى الأبد، ولا شيء يقول كم.
--
-- والتاريخ الثابت يفعل ما أُريد بالحصر — لا أرشيف قديم يبتلع الدفعات —
-- ولا يترك وراءه شيئاً: ما استُخرج بعده يبقى مؤهّلاً حتى يُصنَّف، ولو
-- بعد يومين.
--
-- والقيمة هي يوم الطلب لا يوم النشر على الخادم: من طلب «ابتداءً من تاريخ
-- اليوم» يقصد يومه هو، وما استُخرج بين طلبه ونشر هذا الترحيل يجب أن يدخل
-- التصنيف لا أن يسقط منه.

