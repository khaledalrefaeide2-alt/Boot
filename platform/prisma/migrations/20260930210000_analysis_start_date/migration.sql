    'لا تصنّف المكنسة ما استُخرج قبل هذا التاريخ (لحظة الاستيراد لا تاريخ النشر — فمنشورٌ قديم استُخرج بعده يدخل). اتركه فارغاً لتصفية الأرشيف كلّه. والمستخرج قبله يبقى قابلاً للتصنيف بجولة يدوية في كل حال. الصيغة: YYYY-MM-DD.',
    NOW()
  )
