-- تغطيةٌ كاملة: كلّ منشورٍ مستخرَج يُصنَّف.
--
-- الشكوى كانت أنّ بطاقات اللوحة تقول «غير محسوم»، وسببها شيئان اثنان —
-- أحدهما هنا والآخر في الواجهة:
--
--   ١) جدارُ `analysis.startDate`. وُضع يوم كانت الجولة تبدأ بأقدم منشور
--      في القاعدة: بلا الجدار كانت دفعاتُ اليوم كلّها تُصرف على أرشيفٍ لا
--      ينظر إليه أحد، فلا تبلغ منشورَ الصباح أبداً. والجدار عالج العَرَض
--      وترك العلّة، وثمنُه أنّ كلّ ما استُخرج قبل التاريخ لا يُصنَّف أبداً.
--
--      والعلّة عولجت بعده: الجولة اليوم تبدأ بالأحدث (`orderBy: id desc`)،
--      فمنشورُ هذه الساعة أوّلُ ما يُصنَّف مهما كان خلفه. وبهذا لم يبقَ
--      للجدار عملٌ إلا منعُ ما طلبه صاحب المنصة صراحةً: «التصنيف على كلّ
--      المنشورات المستخرجة». فيُرفع.
--
--   ٢) السقف اليومي ٣٠٠٠. وهو حاجزُ كلفةٍ لا حدُّ طاقة، وكان أقلّ من
--      المتراكم نفسه — فالمكنسة تقف كلّ يوم قبل أن تبلغ آخر الصفّ.
--
--      ★ ورفعُه لا يرفع الكلفة المستقرّة: ما يُصنَّف في اليوم العادي هو
--        ما يُستخرج في اليوم، لا السقف. السقف يحدّ تصفية المتراكم مرّةً
--        واحدة، ويبقى حارساً من الإنفاق غير المقصود.
--
-- ★ والتحديث مشروطٌ بالقيمة القديمة في الحالتين.
--
--   `WHERE "value" = …` تعني: لا تُغيَّر إلا إن كانت لا تزال على ما كتبه
--   ترحيلٌ سابق. فمن غيّرها بقصدٍ من شاشة الإعدادات يبقى تغييرُه — وترحيلٌ
--   يكتب فوق قرار صاحب المنصة أسوأ من ترحيلٍ لا يعمل، لأنه يبدو ناجحاً.

