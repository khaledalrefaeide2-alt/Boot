-- استرجاع الوسائط.
--
-- المصغّرة كانت تُجلب مرّةً واحدة عند الاستيراد، بسقف أربعمئة منشور في
-- التشغيل الواحد، وبلا إعادة محاولة أبداً. فكلّ صورة تعثّر جلبها في تلك
-- اللحظة — انقطاعُ شبكة، أو رفضٌ عابر من المزوّد، أو تشغيلٌ تجاوز السقف —
-- بقيت بلا مصغّرة إلى الأبد. وروابط المنصات موقّعة تنتهي صلاحيتها بعد
-- ساعات، فحين يُكتشف النقص يكون الرابط قد مات ولا سبيل إلى استرجاعه.
--
-- والعدّاد هو ما يجعل إعادة المحاولة ممكنة: بدونه تدور المكنسة في كلّ مرّة
-- على عشرات الآلاف من الروابط الميتة فلا تبلغ الحيّ منها.

-- AlterTable
ALTER TABLE "posts" ADD COLUMN "mediaAttempts"  INTEGER NOT NULL DEFAULT 0;
ALTER TABLE "posts" ADD COLUMN "mediaCheckedAt" TIMESTAMP(3);

-- الفهرس المركّب يخدم استعلام المكنسة: بلا مفتاح، ومحاولاته دون الحدّ،
-- والأحدث أوّلاً. و"mediaKey" أوّله فيخدم البحث بالمفتاح وحده كما كان،
-- فيُستغنى عن الفهرس المفرد بدل أن يُحمَّل الجدول فهرسين متداخلين.
DROP INDEX IF EXISTS "posts_mediaKey_idx";
CREATE INDEX "posts_mediaKey_mediaAttempts_publishedAt_idx"
  ON "posts"("mediaKey", "mediaAttempts", "publishedAt" DESC);

