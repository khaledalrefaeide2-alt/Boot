-- سحب رموز الاستعادة الخام من التنبيهات، وإبطال كلّ رمزٍ لم يُستعمل.
--
-- ★ العلّة: طلب «نسيت كلمة المرور» كان يكتب الرابط الكامل
--   `/reset-password?token=…` في تنبيهٍ يُبثّ لكلّ من دوره ADMIN.
--
--   فكان المدير يستطيع أن يطلب استعادة كلمة مرور المالك ثمّ يفتح الرابط
--   بنفسه. وكان الرمز الخام محفوظاً نصّاً في هذا الجدول — والرموز تُخزَّن
--   في سائر المنصة مجزّأةً بمفتاح الخادم كي لا تكفي نسخةُ القاعدة وحدها.
--
-- التنبيهات القائمة تبقى سجلاً بأنّ الطلب وقع، ويُسحب منها الرابط وحده.
-- والرموز غير المستعملة تُبطل كلّها: لا سبيل إلى التمييز بين رمزٍ كُشف في
-- تنبيه ورمزٍ ولّده مديرٌ لصاحبه — وأقصى ما يكلّفه الإبطال رابطٌ جديد
-- يولَّد من إدارة المستخدمين، وكلّها تنتهي خلال ساعة على أيّ حال.

UPDATE "notifications"
SET "link" = '/admin/users',
    "body" = COALESCE("body", '') || ' — سُحب الرابط لأسباب أمنية؛ ولّد رابطاً جديداً من إدارة المستخدمين.'
WHERE "link" LIKE '/reset-password?token=%';

UPDATE "password_reset_tokens"
SET "usedAt" = NOW()
WHERE "usedAt" IS NULL;
