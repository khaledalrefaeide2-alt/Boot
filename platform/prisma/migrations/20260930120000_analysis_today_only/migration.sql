-- حصر التصنيف التلقائي في مستخرجات اليوم.
--
-- كانت المكنسة تلتقط كلّ منشور بلا تصنيف، فتُصرف دفعاتُ اليوم كلها على
-- أرشيفٍ من عشرات الآلاف: المنشور الوارد قبل ساعة يقف في آخر صفٍّ طوله
-- أيام، واللوحةُ التي تُفتح صباحاً تعرض نسباً محسوبةً على منشورات الأمس.
-- والحصر يقلب الترتيب: الوارد اليوم يُصنَّف اليوم.
--
-- والقياس لحظة الاستيراد (`createdAt`) لا لحظة النشر في المنصة
-- (`publishedAt`): منشورٌ نُشر قبل سنة ودخل قاعدتنا هذا الصباح «مستخرجٌ
-- اليوم» بكل معنى، وهو أوّل ما يُنتظر تصنيفه.
--
-- وثمنُه مذكور: ما استُخرج أمس ولم تبلغه المكنسة — لانقطاع العامل، أو
-- لبلوغ السقف اليومي — يسقط من حسابها عند منتصف الليل ولا تعود إليه.
-- يبقى تصنيفه بجولةٍ يدوية من شاشة التحليل الذكي، وهي بلا هذا الحصر.

-- الإعداد يُكتب هنا لا في ملفّ البذور وحده، فالإنتاج يشغّل
-- `prisma migrate deploy` ولا يشغّل البذور.
INSERT INTO "settings" ("key", "value", "category", "label", "description", "updatedAt")
VALUES
  (
    'analysis.todayOnly',
    'true'::jsonb,
    'analysis',
    'حصر التصنيف التلقائي في منشورات اليوم',
    'تصنّف المكنسة ما استُخرج اليوم وحده (لحظة الاستيراد لا تاريخ النشر). إطفاؤه يجعلها تصفّي المتراكم القديم أيضاً — أسرع في تغطية الأرشيف، وأبطأ في الوصول إلى الوارد الجديد. والمستخرج قبل اليوم يبقى قابلاً للتصنيف بجولة يدوية في كل حال.',
    NOW()
  )
ON CONFLICT ("key") DO NOTHING;

-- والجولة التلقائية القائمة الآن تُلغى.
--
-- الإعداد يحكم ما يأتي بعده لا ما بدأ قبله: جولةٌ سلّمت للعامل مئتَي منشور
-- من الأرشيف تُكمِلها بعد الترحيل كأنّ شيئاً لم يكن. والإلغاء يحفظ ما
-- صُنّف فيها قبل الآن، ودورةُ المكنسة التالية (بعد دقائق) تبدأ محصورةً.
--
-- واليدويّة لا تُمسّ: طلبها إنسانٌ بقصد، ولا يصحّ أن يُلغي ترحيلٌ ما طلبه.
UPDATE "analysis_runs"
SET
  "status"       = 'CANCELLED',
  "finishedAt"   = NOW(),
  "updatedAt"    = NOW(),
  "errorMessage" = 'أُلغيت بحصر التصنيف التلقائي في مستخرجات اليوم'
WHERE "status" IN ('PENDING', 'RUNNING')
  AND "trigger" = 'AUTO';
