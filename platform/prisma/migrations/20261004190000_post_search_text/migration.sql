-- نصّ البحث: عمودٌ مطبَّع يُبحث فيه، بدل خمسة حقول خام.
--
-- ★ العلّة الأولى: المنصة تطبّع عند الاستيراد ولا تطبّع عند البحث.
--
--   `detectKeywords` تطابق «وزارة الكهرباء» في منشورٍ كُتب فيه «وزاره
--   الكهربا» — تُطبّع الطرفين ثمّ تقارن. وسطرُ البحث يطابق النصّ الخام
--   كما هو: فالكلمة التي ربطت المنشور بكلمةٍ مفتاحية لا يجدها من يكتبها
--   في الشاشة. وهو فرقٌ لا يُشتكى منه لأنه لا يُرى — الموظّف يرى نتائج،
--   ولا يرى ما لم يظهر.
--
-- ★ والعلّة الثانية: خمسة حقول بـ`OR` لكلّ حدّ.
--
--   ومع المرادفات صار الحدّ مجموعة: عشرة مرادفات في خمسة حقول = خمسون
--   شرط `LIKE` للمجموعة الواحدة، وثماني مجموعاتٍ أربعمئة. فتُجمع
--   الأربعة التي تخصّ المنشور في عمودٍ واحد — ويبقى اسم الحساب شرطاً
--   مستقلّاً لأنه في جدولٍ آخر ويتغيّر باسم الحساب لا بالمنشور.
--
-- ★ والتطبيع هنا بـSQL لا بالعُقدة.
--
--   الملء يمسّ كلّ صفٍّ في الجدول، وتمريرُه صفّاً صفّاً عبر التطبيق
--   يحوّل ترحيلاً من ثوانٍ إلى ساعة. والثمن أنّ القاعدة مكتوبةٌ في
--   موضعين — هنا وفي `normalizeForSearch` — فيُقارَن الاثنان على قاعدة
--   حقيقية في `verify:search-text`، ومن غيّر أحدهما ونسي الآخر يسقط
--   الفحص.

ALTER TABLE "posts" ADD COLUMN "searchText" TEXT;

-- نظيرُ `normalizeForSearch` حرفاً بحرف:
--
--   regexp_replace  إزالة التطويل (0640) والتشكيل (064B..065F) والسكون
--                   الخنجريّ (0670) — ولا تمسّ الأرقام العربية (0660..0669)
--   translate       أ إ آ ٱ ← ا  ·  ى ← ي  ·  ة ← ه  ·  ؤ ئ ← ء
--                   ثمّ ٠..٩ و۰..۹ ← 0..9، فصور الرقم الثلاث صورةٌ واحدة
--   regexp_replace  توحيد المسافات — والعمود مجموعٌ من حقول بعضها فارغ
--   lower + btrim   كما في الدالّة
--
-- والترتيب نفسه الذي تجمع به `buildSearchText`: النصّ، فاسم الكاتب،
-- فالهاشتاغات، فالكلمات المكتشفة.
UPDATE "posts"
SET "searchText" = left(
  btrim(
    regexp_replace(
      lower(
        translate(
          regexp_replace(
            concat_ws(
              ' ',
              coalesce("text", ''),
              coalesce("authorName", ''),
              array_to_string("hashtags", ' '),
              array_to_string("detectedKeywords", ' ')
            ),
            '[ـً-ٰٟ]',
            '',
            'g'
          ),
          'أإآٱىةؤئ٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹',
          'اااايهءء01234567890123456789'
        )
      ),
      '\s+',
      ' ',
      'g'
    )
  ),
  20000
);

-- CreateIndex
-- فهرس ثلاثيّات: هو ما يجعل `LIKE '%…%'` مسحَ فهرسٍ لا مسحَ جدول.
-- والامتداد مثبَّت من ترحيلٍ سابق — فهرس النصّ الخام يقوم عليه.
CREATE INDEX "posts_searchText_trgm_idx" ON "posts" USING GIN ("searchText" gin_trgm_ops);
