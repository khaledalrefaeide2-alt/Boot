-- طابور التصنيف يصير شيئاً قائماً بذاته، لا استنتاجاً من غياب صفّ.
--
-- ترتيب «الأحدث أوّلاً» صحّ ثلاث مرّات وانكسر ثلاث مرّات: في مكنسة
-- الأحداث، ثمّ في جولة التحليل، ولا يزال مكسوراً في مكنسة الفهرسة
-- الدلالية. وفي كلّ مرّة كُتب الترتيب من جديد في موضعه، فلا شيء يربط
-- المواضع ولا شيء يكشف انكسار أحدها. وهذا الترحيل يعالج السبب لا العَرَض:
--
--   ١) عمودٌ `analyzedAt` على المنشور نفسه. «ما ينتظر التصنيف» كان يُسأل
--      بضمٍّ معاكس على جدول التحاليل (`analysis IS NULL`)، وهو سؤالٌ لا
--      فهرس له: كلّما صُنّف أوّلُ الطابور وجب على القاعدة أن تمرّ على ما
--      صُنّف قبله لتبلغ ما لم يُصنَّف. فالاستعلام يبطؤ كلّما تقدّم العمل —
--      وهو أسوأ شكلٍ للبطء، لأنه يظهر بعد أشهر وعلى أكبر قاعدة.
--
--   ٢) فهرسٌ على (`analyzedAt`, `publishedAt DESC`). بادئتُه تحصر المسح في
--      المنتظرين، وترتيبُه داخلها هو ترتيب الطابور نفسه — فالقراءة مسحُ
--      فهرسٍ من أوّله، لا فرزاً لعشرات الآلاف.
--
--      ويضيق الفهرس كلّما صُنّف منشور: حين يفرغ الطابور يصير فارغاً، فلا
--      يكلّف شيئاً مهما كبر جدول المنشورات.
--
-- والقيمة تُملأ من جدول التحاليل القائم، فلا يُقرأ منشورٌ مصنَّف كأنه
-- منتظر فيُصنَّف مرّةً ثانية بثمنٍ ثانٍ.

ALTER TABLE "posts" ADD COLUMN "analyzedAt" TIMESTAMP(3);

-- الملء من الصفوف القائمة.
--
-- و`updatedAt` لا `createdAt`: الصفّ يُحدَّث عند إعادة التصنيف، فهو «آخر
-- مرّة مرّ فيها المنشور على التصنيف» — وهو بالضبط معنى العمود الجديد،
-- وعليه يقوم حدُّ «أعد تصنيف ما صُنّف قبل كذا».
UPDATE "posts" AS p
SET "analyzedAt" = a."updatedAt"
FROM "post_analyses" AS a
WHERE a."postId" = p."id";

-- CreateIndex
CREATE INDEX "posts_analyzedAt_publishedAt_idx"
  ON "posts" ("analyzedAt", "publishedAt" DESC);
