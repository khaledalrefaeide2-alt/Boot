-- مزامنة حكم المنشور مع صفّ تحليله.
--
-- ★ العلّة: شرطٌ بمنطق SQL الثلاثيّ أسقط كلّ منشورٍ جديد.
--
--   كانت طبقة الحفظ تكتب الحكم على المنشور بشرط
--   `NOT (sentimentSource = 'MANUAL')` — حمايةً لتصحيح المراجع من أن
--   تكتب فوقه جولةٌ لاحقة. وهي في SQL تساوي NULL لا TRUE حين يكون
--   العمود فارغاً، والصفّ لا يُطابَق إلا بـTRUE.
--
--   وكلّ منشورٍ وارد عمودُه فارغ (`AnalysisSource?` في المخطّط). فكان
--   صفّ التحليل يُكتب صحيحاً ويبقى `posts.sentiment` على 'UNKNOWN'
--   إلى الأبد.
--
--   وأثرُه لم يكن في البطاقة وحدها: الفلترة بالمشاعر، ونسب اللوحات،
--   وإحصاءات اليوم، والتقارير — كلّها تقرأ هذا العمود. فكانت تُحسب على
--   حقلٍ لم يُكتب قطّ منذ بدأ التصنيف بالذكاء الاصطناعي.
--
--   ولم يُكتشف لأنّ المنشورات القديمة لها `sentimentSource = 'RULES'`
--   من محرّك القواعد القديم — فهي وحدها كانت تُحدَّث، فبدا الأمر
--   تفاوتاً في التصنيف لا عطباً في الكتابة.
--
-- وهذا يصحّح ما تراكم: يُنسخ حكم التحليل إلى المنشور لكلّ صفٍّ اختلفا
-- فيه، ولا يُمسّ ما صحّحه إنسان.

UPDATE "posts" AS p
SET
  "sentiment"      = a."sentiment",
  "sentimentScore" = a."confidence",
  "sentimentSource" = 'AI'
FROM "post_analyses" AS a
WHERE a."postId" = p."id"
  -- ما صحّحه مراجع يبقى كما قرّره — وهو ما أراده الشرط الأصلي
  AND p."sentimentSource" IS DISTINCT FROM 'MANUAL'
  -- ولا تُلمَس الصفوف المتطابقة أصلاً: تحديثٌ بلا تغيير يُضخّم الجدول بلا داعٍ
  AND (p."sentiment" IS DISTINCT FROM a."sentiment"
       OR p."sentimentSource" IS DISTINCT FROM 'AI');
