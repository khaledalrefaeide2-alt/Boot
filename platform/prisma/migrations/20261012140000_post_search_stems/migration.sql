-- تجذيرٌ خفيف لعمود البحث — من مطابقة الجزء إلى مطابقة الكلمة.
--
-- ★ العلّة: `LIKE '%حدّ%'` تُطابق أيّ موضعٍ في أيّ كلمة.
--
--   قياسٌ على عشر حالات حقيقية أعطى أربع مطابقاتٍ خاطئة:
--
--     «علم» تجد «المعلم»   ·   «نار» تجد «الدينار»
--     «شفى» تجد «مستشفى»   ·   «الة» تجد «حالة»
--
--   وفي منصّة رصد يعني ذلك أنّ البحث عن «نار» يُرجع كلّ منشورٍ فيه
--   «دينار»، فيُقرأ العدد ارتفاعاً في موضوعٍ لم يُذكر.
--
-- ★ ولا يكفي أن تُطابَق الكلمة كاملةً.
--
--   العربية تُلصق أدواتها: «الوزارة» و«بالوزارة» و«والوزارة» كلمةٌ
--   واحدة بثلاث صور. فمطابقةُ الكلمة كاملةً تُصلح الدقّة وتُفسد
--   الاسترجاع. فيُجرَّد اللصيق من الطرفين — في النصّ وفي الحدّ معاً —
--   ثمّ تُطابَق الكلمة كاملةً.
--
-- ★ والعمود يُحاط بمسافة من طرفيه، وهو ما يجعل المطابقة على الكلمة:
--   `LIKE '% نار %'` لا تُطابق «دينار» لأنّ ما قبل «نار» فيها ليس مسافة.
--
-- ★ والقاعدة مكتوبةٌ هنا وفي `lightStem` معاً، فيُشغَّل هذا التعبير
--   نفسه في `verify:queue` ويُقارَن ناتجُه بناتج الدالّة حرفاً بحرف.
--   ومن غيّر أحدهما ونسي الآخر يسقط الفحص.

-- والبناء: تجريدُ السوابق مرّة، ثمّ اللواحق ثلاث مرّات.
--
-- ★ والتكرار شرطُ صحّة لا ضبط: المجذّر يجب أن يكون ثابتاً
--   (`stem(stem(x)) = stem(x)`)، وإلا افترق النصّ عن الحدّ ولم يلتقيا.
--   و«تقنيناً» تمرّ بقاعدة الألف فتقف عند «تقنين»، والحدّ «تقنين» يمرّ
--   بقاعدة الجمع فيصير «تقن» — فلا يجد شيئاً. والتكرار يجعلهما يلتقيان.
--
-- واللواحق بالترتيب: جمعُ المذكّر والمؤنّث، ثمّ ألفُ التنوين، ثمّ
-- التاء المربوطة.

