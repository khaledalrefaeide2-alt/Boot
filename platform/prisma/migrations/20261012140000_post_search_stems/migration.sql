  CASE
    WHEN btrim(coalesce("searchText", '')) = '' THEN ''
    ELSE ' ' || btrim(
regexp_replace(
  regexp_replace(
    regexp_replace(
      regexp_replace(
  regexp_replace(
    regexp_replace(
      regexp_replace(
  regexp_replace(
    regexp_replace(
      regexp_replace(
  ' ' || btrim("searchText") || ' ',
  '( )(وبال|فبال|وكال|وال|فال|بال|كال|ولل|لل|ال)([^ ]{3,})',
  '\1\3',
  'g'
),
      '([^ ]{3,})(ات|ون|ين)( )', '\1\3', 'g'
    ),
    '([^ ]{4,})ا( )', '\1\2', 'g'
  ),
  '([^ ]{4,})ه( )', '\1\2', 'g'
),
      '([^ ]{3,})(ات|ون|ين)( )', '\1\3', 'g'
    ),
    '([^ ]{4,})ا( )', '\1\2', 'g'
  ),
  '([^ ]{4,})ه( )', '\1\2', 'g'
),
      '([^ ]{3,})(ات|ون|ين)( )', '\1\3', 'g'
    ),
    '([^ ]{4,})ا( )', '\1\2', 'g'
  ),
  '([^ ]{4,})ه( )', '\1\2', 'g'
)
    ) || ' '
  END
WHERE "searchText" IS NOT NULL;
